// Regenerates riv-defs.json from a rive-runtime checkout's include/rive/generated headers.
// Usage: node tools/riv-inspect/gen-defs.mjs <path-to-rive-runtime> <commit-sha>
// Only reads local files; performs no network or shell actions.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [root, commit] = process.argv.slice(2);
if (!root || !commit) throw new Error('usage: gen-defs.mjs <rive-runtime> <commit>');
const base = join(root, 'include/rive/generated');
const files = [];
(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path);
    else if (entry.endsWith('_base.hpp')) files.push(path);
  }
})(base);

const types = {};
const properties = {};
const owners = new Map(); // "OwnerBase::name" -> key
for (const file of files) {
  const text = readFileSync(file, 'utf8');
  const cls = /class (\w+)Base : public (\w+)/.exec(text);
  if (!cls) continue;
  const typeKey = /static const uint16_t typeKey = (\d+);/.exec(text);
  if (typeKey) types[typeKey[1]] = { name: cls[1], parent: cls[2] };
  for (const match of text.matchAll(/static const uint16_t (\w+)PropertyKey = (\d+);/g)) {
    owners.set(cls[1] + 'Base::' + match[1], match[2]);
    properties[match[2]] ??= { owner: cls[1], name: match[1], type: 'unknown' };
  }
}

// The registry's propertyFieldId switch is the authoritative serialized type for every key,
// including aliases (e.g. Node.xArtboard) that share a key with another class's field.
const registryTypes = {
  CoreIdType: 'uint',
  CoreIntType: 'uint',
  CoreUintType: 'uint',
  CoreStringType: 'string',
  CoreColorType: 'color',
  CoreBoolType: 'bool',
  CoreDoubleType: 'double',
  CoreBytesType: 'bytes',
};
const registry = readFileSync(join(base, 'core_registry.hpp'), 'utf8');
const section = registry.slice(registry.indexOf('static int propertyFieldId'));
let pending = [];
for (const line of section.split('\n')) {
  const kase = /case (\w+Base::\w+)PropertyKey:/.exec(line);
  if (kase) pending.push(kase[1]);
  const ret = /return (Core\w+Type)::id;/.exec(line);
  if (ret) {
    for (const name of pending) {
      const key = owners.get(name);
      if (key) properties[key].type = registryTypes[ret[1]] ?? ret[1];
    }
    pending = [];
  }
  if (/return -1;/.test(line)) break;
}

const out = {
  source: 'https://github.com/rive-app/rive-runtime/tree/' + commit + '/include/rive/generated',
  commit,
  types,
  properties,
};
writeFileSync(new URL('./riv-defs.json', import.meta.url), JSON.stringify(out) + '\n');

// Compact backing-type table for the in-browser patcher (0 uint/bool, 1 string/bytes, 2 double, 3 color).
const code = { uint: 0, bool: 0, string: 1, bytes: 1, double: 2, color: 3 };
const entries = Object.entries(properties)
  .filter(([, p]) => p.type in code)
  .map(([key, p]) => key + ':' + code[p.type]);
writeFileSync(
  new URL('../../src/renderer/attachments/riv/fieldTypes.generated.ts', import.meta.url),
  '// Generated by tools/riv-inspect/gen-defs.mjs from rive-runtime ' +
    commit +
    '. Do not edit.\n' +
    '// Backing type per core property key: 0 uint/bool/id, 1 string/bytes, 2 float32, 3 color.\n' +
    'export const fieldTypes: Readonly<Record<number, 0 | 1 | 2 | 3>> = {' +
    entries.join(',') +
    '};\n',
);
const unknown = Object.values(properties).filter((p) => p.type === 'unknown').length;
console.log(
  Object.keys(types).length,
  'types',
  Object.keys(properties).length,
  'properties',
  unknown,
  'untyped',
);
