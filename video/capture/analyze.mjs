// Measures captured Tavi shots so the composition can follow and time them:
//   box     her bounding box per frame (0..1 of the capture), for cameras that track her
//   energy  how much she moved since the previous frame, for landing cuts on the action
// Writes src/generated/<shot>.json. Usage: node capture/analyze.mjs [shot...] (from video/)
import { chromium } from '@playwright/test';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { shots } from './shots.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const footage = join(here, '..', 'public', 'footage', 'tavi');
const out = join(here, '..', 'src', 'generated');
await mkdir(out, { recursive: true });
const names = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(shots);

const browser = await chromium.launch({ args: ['--allow-file-access-from-files'] });
const page = await browser.newPage();
await page.goto(pathToFileURL(footage).href + '/');
for (const name of names) {
  const meta = JSON.parse(await readFile(join(footage, name, 'meta.json'), 'utf8'));
  const result = await page.evaluate(
    async ({ dir, frames }) => {
      const width = 384;
      let height = 0;
      let ctx = null;
      let previous = null;
      const box = [];
      const energy = [];
      for (let i = 0; i < frames; i++) {
        const img = new Image();
        img.src = `${dir}/${String(i).padStart(5, '0')}.png`;
        await img.decode();
        if (!ctx) {
          height = Math.round((width * img.height) / img.width);
          const canvas = document.createElement('canvas');
          canvas.width = width;
          canvas.height = height;
          ctx = canvas.getContext('2d', { willReadFrequently: true });
        }
        ctx.clearRect(0, 0, width, height);
        ctx.drawImage(img, 0, 0, width, height);
        const data = ctx.getImageData(0, 0, width, height).data;
        let x0 = width;
        let y0 = height;
        let x1 = -1;
        let y1 = -1;
        let moved = 0;
        for (let y = 0; y < height; y++)
          for (let x = 0; x < width; x++) {
            const p = (y * width + x) * 4;
            // Opaque body pixels only; the soft floor shadow stays under the threshold.
            if (data[p + 3] > 200 && data[p] + data[p + 1] + data[p + 2] > 60) {
              if (x < x0) x0 = x;
              if (x > x1) x1 = x;
              if (y < y0) y0 = y;
              if (y > y1) y1 = y;
            }
            if (previous)
              moved +=
                Math.abs(data[p] - previous[p]) +
                Math.abs(data[p + 1] - previous[p + 1]) +
                Math.abs(data[p + 2] - previous[p + 2]) +
                Math.abs(data[p + 3] - previous[p + 3]);
          }
        const r = (v) => Math.round(v * 1000) / 1000;
        box.push(
          x1 < 0
            ? null
            : [r(x0 / width), r(y0 / height), r((x1 + 1) / width), r((y1 + 1) / height)],
        );
        energy.push(previous ? Math.round((moved / (width * height)) * 100) / 100 : 0);
        previous = data;
      }
      return { box, energy };
    },
    { dir: pathToFileURL(join(footage, name)).href, frames: meta.frames },
  );
  await writeFile(join(out, `${name}.json`), JSON.stringify({ name, fps: meta.fps, ...result }));
  const busy = result.energy.filter((e) => e > 0.5).length;
  console.log(`${name}: ${String(meta.frames)} frames, moving in ${String(busy)}`);
}
await browser.close();

// An index of every measured shot, so the composition can import them statically.
const measured = (await readdir(out)).filter((file) => file.endsWith('.json')).sort();
const lines = [
  '// Generated by capture/analyze.mjs; do not edit.',
  ...measured.map((file, i) => `import m${String(i)} from './${file}';`),
  '',
  'export const measured: Record<string, { fps: number; box: (number[] | null)[]; energy: number[] }> = {',
  ...measured.map((file, i) => `  '${file.replace('.json', '')}': m${String(i)},`),
  '};',
  '',
];
await writeFile(join(out, 'index.ts'), lines.join('\n'));
